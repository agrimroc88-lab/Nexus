--
-- Un mapa por base y tipo (evacuacion | riesgos). Lo propio del mapa
-- se guarda aquí; los edificios, cuartos y señalética se LEEN del
-- croquis y de los planos (no se tocan).
--   terreno    = contorno del terreno [[x,y], …]
--   elementos  = flechas, rutas, vías, textos, señales, «usted está aquí»
--   controles  = texto de «Control del riesgo» por tipo de señal
-- =====================================================================

do $$
declare
  t_emp  text;
  t_base text;
  t_user text;
begin
  select format_type(atttypid, atttypmod) into t_emp
  from pg_attribute where attrelid = 'public.viv_bases'::regclass and attname = 'empresa_id';
  select format_type(atttypid, atttypmod) into t_base
  from pg_attribute where attrelid = 'public.viv_bases'::regclass and attname = 'id';
  select format_type(atttypid, atttypmod) into t_user
  from pg_attribute where attrelid = 'public.viv_espacios'::regclass and attname = 'creado_por';
  t_user := coalesce(t_user, 'uuid');

  if to_regclass('public.viv_mapas') is null then
    execute format($f$
      create table public.viv_mapas (
        id                bigint generated by default as identity primary key,
        empresa_id        %s not null,
        base_id           %s not null references public.viv_bases(id) on delete cascade,
        tipo              text not null check (tipo in ('evacuacion', 'riesgos')),
        titulo            text,
        elaborado_nombre  text,
        elaborado_cargo   text,
        elaborado_entidad text,
        fecha             date not null default current_date,
        terreno           jsonb not null default '[]'::jsonb,
        elementos         jsonb not null default '[]'::jsonb,
        controles         jsonb not null default '{}'::jsonb,
        activo            boolean not null default true,
        creado_en         timestamptz not null default now(),
        actualizado_en    timestamptz not null default now(),
        creado_por        %s,
        modificado_por    %s,
        constraint viv_mapas_json_chk check (
          jsonb_typeof(terreno) = 'array' and jsonb_typeof(elementos) = 'array' and jsonb_typeof(controles) = 'object')
      )$f$, t_emp, t_base, t_user, t_user);
  end if;
end $$;

create unique index if not exists viv_mapas_base_tipo_uq on public.viv_mapas (base_id, tipo) where activo;

alter table public.viv_mapas enable row level security;
drop policy if exists "viv_mapas acceso app" on public.viv_mapas;
create policy "viv_mapas acceso app" on public.viv_mapas for all using (true) with check (true);
grant select, insert, update, delete on public.viv_mapas to anon, authenticated;

