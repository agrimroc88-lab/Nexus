-- Catálogo de áreas de cada empresa (Mecánicos, Choferes, Cocina…)
-- con su dibujo y su color. Cada habitación puede tener un área: se
-- muestra encima de la habitación en el tablero y en el plano.
-- Usa la misma seguridad que las demás tablas de habitaciones.
-- =====================================================================

do $$
declare
  t_emp  text;
  t_user text;
begin
  -- Mismos tipos de columna que viv_espacios (empresa y autoría)
  select format_type(atttypid, atttypmod) into t_emp
  from pg_attribute where attrelid = 'public.viv_espacios'::regclass and attname = 'empresa_id';
  select format_type(atttypid, atttypmod) into t_user
  from pg_attribute where attrelid = 'public.viv_espacios'::regclass and attname = 'creado_por';
  t_user := coalesce(t_user, 'uuid');

  if to_regclass('public.viv_areas') is null then
    execute format($f$
      create table public.viv_areas (
        id             bigint generated by default as identity primary key,
        empresa_id     %s not null,
        nombre         text not null check (length(trim(nombre)) between 2 and 40),
        icono          text not null default '🏷️' check (length(icono) between 1 and 16),
        color          text not null default '#1F5FA8' check (color ~* '^#[0-9a-f]{6}$'),
        orden          integer not null default 0,
        activo         boolean not null default true,
        creado_en      timestamptz not null default now(),
        creado_por     %s,
        modificado_por %s
      )$f$, t_emp, t_user, t_user);
  end if;
end $$;

create index if not exists viv_areas_empresa_idx on public.viv_areas (empresa_id, activo);

alter table public.viv_espacios
  add column if not exists area_id bigint references public.viv_areas(id) on delete set null;

-- Misma regla de acceso que viv_espacios ("acceso app")
alter table public.viv_areas enable row level security;
drop policy if exists "viv_areas acceso app" on public.viv_areas;
create policy "viv_areas acceso app" on public.viv_areas for all using (true) with check (true);
grant select, insert, update, delete on public.viv_areas to anon, authenticated;

-- Verificación
select 'viv_areas' as tabla, count(*) as filas from public.viv_areas
union all
select 'viv_espacios.area_id', count(*) from information_schema.columns
where table_schema = 'public' and table_name = 'viv_espacios' and column_name = 'area_id';
