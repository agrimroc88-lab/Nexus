-- Ejecutar UNA vez en Supabase de NEXUS → SQL Editor.
-- Es seguro ejecutarlo más de una vez. No borra ni cambia datos.
--
-- Inodoros, duchas, lavamanos, urinarios, lavaderos y espejos de cada
-- baño (o lavandería), cada uno con su nombre ("Ducha 2") y su estado:
-- ok (funciona) · reparacion (en reparación) · danada (dañada).
-- Posición dentro del cuarto en el plano: plano_px / plano_py (0–100 %).
-- Usa la misma seguridad que las demás tablas de habitaciones.
-- =====================================================================

do $$
declare
  t_emp  text;
  t_esp  text;
  t_user text;
begin
  select format_type(atttypid, atttypmod) into t_emp
  from pg_attribute where attrelid = 'public.viv_espacios'::regclass and attname = 'empresa_id';
  select format_type(atttypid, atttypmod) into t_esp
  from pg_attribute where attrelid = 'public.viv_espacios'::regclass and attname = 'id';
  select format_type(atttypid, atttypmod) into t_user
  from pg_attribute where attrelid = 'public.viv_espacios'::regclass and attname = 'creado_por';
  t_user := coalesce(t_user, 'uuid');

  if to_regclass('public.viv_piezas') is null then
    execute format($f$
      create table public.viv_piezas (
        id             bigint generated by default as identity primary key,
        empresa_id     %s not null,
        espacio_id     %s not null references public.viv_espacios(id) on delete cascade,
        tipo           text not null check (length(tipo) between 2 and 30),
        nombre         text not null check (length(trim(nombre)) between 1 and 40),
        estado         text not null default 'ok' check (estado in ('ok', 'reparacion', 'danada')),
        nota           text,
        plano_px       numeric(5,2) check (plano_px is null or plano_px between 0 and 100),
        plano_py       numeric(5,2) check (plano_py is null or plano_py between 0 and 100),
        orden          integer not null default 0,
        activo         boolean not null default true,
        creado_en      timestamptz not null default now(),
        creado_por     %s,
        modificado_por %s
      )$f$, t_emp, t_esp, t_user, t_user);
  end if;
end $$;

create index if not exists viv_piezas_espacio_idx on public.viv_piezas (espacio_id, activo);
create index if not exists viv_piezas_empresa_idx on public.viv_piezas (empresa_id, activo);

alter table public.viv_piezas enable row level security;
drop policy if exists "viv_piezas acceso app" on public.viv_piezas;
create policy "viv_piezas acceso app" on public.viv_piezas for all using (true) with check (true);
grant select, insert, update, delete on public.viv_piezas to anon, authenticated;

